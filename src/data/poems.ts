/**
 * Получить стих по id
 */
export function getPoem(id: string): Poem | undefined {
  return poems.find((p) => p.id === id);
}

/**
 * Получить стих по slug (URL-путь)
 */
export function getPoemBySlug(slug: string): Poem | undefined {
  return poems.find((p) => p.slug === slug);
}

/**
 * Получить следующий стих(и) по id текущего
 */
export function getNextPoems(currentId: string): Poem[] {
  const nextIds = graph[currentId] || [];
  return nextIds.map(getPoem).filter(Boolean) as Poem[];
}

/**
 * Получить предыдущий стих(и) по id текущего
 */
export function getPrevPoems(currentId: string): Poem[] {
  const prevIds = prevMap[currentId] || [];
  return prevIds.map(getPoem).filter(Boolean) as Poem[];
}
